"""Sphinx configuration for the tambora documentation.

The API reference is generated by autodoc/autosummary directly from tambora's
docstrings, so it can never drift from the installed package. The version this
builds against is whatever ``pip install tambora`` put in the environment --
pin it in ``requirements.txt`` when cutting a docs release.
"""

import os
from datetime import date

import tambora

# -- Project ----------------------------------------------------------------

project = "tambora"
author = "Gabriel Pfaffman"
copyright = f"{date.today().year}, {author}"

release = tambora.__version__
version = release.split("+")[0]

# -- General ----------------------------------------------------------------

