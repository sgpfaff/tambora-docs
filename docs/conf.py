autodoc_class_signature = "mixed"
autodoc_typehints = "description"
autodoc_typehints_description_target = "documented_params"

# galpy is an optional dependency at runtime but required to document the galpy
# bridge; if it is genuinely missing, stub it rather than failing the build.
autodoc_mock_imports = []
try:
    import galpy  # noqa: F401
except ImportError:  # pragma: no cover
    autodoc_mock_imports.append("galpy")

napoleon_google_docstring = False
napoleon_numpy_docstring = True
napoleon_use_rtype = False
napoleon_preprocess_types = True

