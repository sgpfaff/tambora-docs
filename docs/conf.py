nb_execution_timeout = 900
nb_execution_raise_on_error = True
nb_execution_excludepatterns = [
    # The N-body-heavy notebooks ship with committed outputs, regenerated by
    # tools/build_notebooks.py. Keep this list in sync with EXECUTE there.
    "examples/04-tidal-stream.ipynb",
    "examples/05-tidal-stripping.ipynb",
    "examples/06-stream-track.ipynb",
    "examples/07-stream-gaps.ipynb",
    "examples/08-ring-galaxy.ipynb",
    "examples/09-disk-instability.ipynb",
]

# The .py sources next to each notebook are jupytext mirrors, not pages.
exclude_patterns += ["examples/*.py"]

